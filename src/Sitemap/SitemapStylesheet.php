<?php
/** Human-friendly XSL stylesheet for the XML sitemaps. */
namespace PublishRankSEO\Sitemap;

use PublishRankSEO\Core\Branding;

final class SitemapStylesheet {
	public function register() {
		add_action( 'init', array( $this, 'rewrite' ) );
		add_action( 'template_redirect', array( $this, 'render' ), 1 );
	}

	public function rewrite() {
		add_rewrite_tag( '%publishrank_xsl%', '([0-1])' );
		add_rewrite_rule( '^publishrank-sitemap\.xsl$', 'index.php?publishrank_xsl=1', 'top' );
	}

	/** Root-relative URL so the browser treats it as same-origin. */
	public static function url() {
		return wp_make_link_relative( home_url( '/publishrank-sitemap.xsl' ) );
	}

	public function render() {
		if ( '1' !== (string) get_query_var( 'publishrank_xsl' ) ) {
			return;
		}
		status_header( 200 );
		header( 'Content-Type: application/xml; charset=UTF-8' );
		header( 'X-Robots-Tag: noindex' );
		header( 'Cache-Control: public, max-age=3600' );
		echo str_replace( array( '%%LOGO%%', '%%CSS%%' ), array( esc_url( Branding::image( 'icon-128x128.png' ) ), esc_url( Branding::asset_url( 'css/sitemap.css' ) ) ), self::xsl() ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
		exit;
	}

	private static function xsl() {
		return <<<'XSL'
<?xml version="1.0" encoding="UTF-8"?>
<xsl:stylesheet version="1.0"
	xmlns:xsl="http://www.w3.org/1999/XSL/Transform"
	xmlns:sm="http://www.sitemaps.org/schemas/sitemap/0.9"
	xmlns:news="http://www.google.com/schemas/sitemap-news/0.9"
	xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"
	xmlns:video="http://www.google.com/schemas/sitemap-video/1.1"
	exclude-result-prefixes="sm news image video">
<xsl:output method="html" encoding="UTF-8" indent="yes"/>
<xsl:template match="/">
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<meta name="robots" content="noindex"/>
<title>XML Sitemap - PublishRank</title>
	<link rel="stylesheet" type="text/css" href="%%CSS%%" />
</head>
<body>
<header>
<img src="%%LOGO%%" alt="PublishRank"/>
<div><h1>XML Sitemap</h1><p>Generated by PublishRank - Advanced Sitemap &amp; SEO Plugin, built for news sites.</p></div>
</header>
<main>
<xsl:choose>
<xsl:when test="sm:sitemapindex">
<p class="meta">This index lists <strong><xsl:value-of select="count(sm:sitemapindex/sm:sitemap)"/></strong> sitemap file(s).</p>
<table>
<thead><tr><th>#</th><th>Sitemap</th><th>Last modified</th></tr></thead>
<tbody>
<xsl:for-each select="sm:sitemapindex/sm:sitemap">
<tr>
<td><xsl:value-of select="position()"/></td>
<td><a href="{sm:loc}"><xsl:value-of select="sm:loc"/></a></td>
<td><xsl:if test="sm:lastmod"><xsl:value-of select="concat(substring(sm:lastmod,1,10),' ',substring(sm:lastmod,12,5))"/></xsl:if></td>
</tr>
</xsl:for-each>
</tbody>
</table>
</xsl:when>
<xsl:when test="sm:urlset">
<p class="meta">This sitemap contains <strong><xsl:value-of select="count(sm:urlset/sm:url)"/></strong> URL(s).</p>
<table>
<thead><tr><th>#</th><th>URL</th><th>News title</th><th>Images</th><th>Videos</th><th>Last modified</th></tr></thead>
<tbody>
<xsl:for-each select="sm:urlset/sm:url">
<tr>
<td><xsl:value-of select="position()"/></td>
<td><a href="{sm:loc}"><xsl:value-of select="sm:loc"/></a></td>
<td><xsl:value-of select="news:news/news:title"/></td>
<td><xsl:value-of select="count(image:image)"/></td>
<td><xsl:value-of select="count(video:video)"/></td>
<td><xsl:if test="sm:lastmod"><xsl:value-of select="concat(substring(sm:lastmod,1,10),' ',substring(sm:lastmod,12,5))"/></xsl:if></td>
</tr>
</xsl:for-each>
</tbody>
</table>
</xsl:when>
</xsl:choose>
</main>
<footer>Search engines read the raw XML; this styled view is only for people.</footer>
</body>
</html>
</xsl:template>
</xsl:stylesheet>
XSL;
	}
}
